CREATE DATABASE ShopDB;

USE ShopDB;

CREATE TABLE Products (
	ID INT,
    Name VARCHAR(50),
    Description VARCHAR(100),
    Price INT,
    WarehouseAmount INT
);

CREATE TABLE Customers (
	ID INT, 
    FirstName VARCHAR(50),
    LastName VARCHAR(50),
    Email VARCHAR(100),
    Address VARCHAR(100)
);

CREATE TABLE Orders (
	ID INT, 
    CustomerID INT,
    Date DATE
);

CREATE TABLE OrderItems (
	ID INT,
    OrderID INT,
    ProductID INT
);

